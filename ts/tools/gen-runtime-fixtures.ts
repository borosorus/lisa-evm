/**
 * Generates build/fixtures/tooling.json: representative LISA programs compiled
 * through the full TypeScript toolchain, for the Foundry runtime-compat suite
 * (test/LISATooling.t.sol) to execute against the real Yul runtime.
 *
 * Programs are address-free (no embedded addresses; the Solidity side appends
 * its own write-top-to-`a` tail when a value check is requested), so the
 * fixtures stay valid regardless of where the runtime is deployed.
 *
 * Usage: node ts/tools/gen-runtime-fixtures.ts
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { Program } from '../src/ast.ts';
import { compile } from '../src/compile.ts';
import { decode } from '../src/decode.ts';
import {
  add,
  blob,
  div,
  dup,
  eq,
  jmp,
  jz,
  keccak256,
  label,
  mload,
  mul,
  mstore,
  pop,
  program,
  push,
  raw,
  stop,
  sub,
  swap,
} from '../src/api.ts';

interface Fixture {
  name: string;
  program: Uint8Array;
  expect: 'ok' | 'revert';
  /** When set, the Solidity harness writes the stack top to `a` and asserts it. */
  expectA?: bigint;
}

const fixtures: Fixture[] = [];
function addFixture(name: string, body: Program, expect: 'ok' | 'revert', expectA?: bigint): void {
  // With expectA, the Foundry harness appends its own write-top-to-`a` tail
  // (ending in CALL+STOP), so the body must fall through into it; a trailing
  // STOP would end execution before the tail runs.
  const bytes = compile(program(body, expectA === undefined ? stop : [])).bytes;
  // Self-check: decodable generated bytecode must survive a decode round-trip.
  try {
    for (const instr of decode(bytes)) void instr;
  } catch (err) {
    if (expect !== 'revert') throw err;
  }
  fixtures.push({ name, program: bytes, expect, expectA });
}

// --- Math and stack ---------------------------------------------------------

addFixture('math_add', program(push(2), push(3), add), 'ok', 5n);
// SUB pops b then a: [3,1] -> 3 - 1.
addFixture('math_sub', program(push(3), push(1), sub), 'ok', 2n);
addFixture('math_mul', program(push(0xff), push(0x100), mul), 'ok', 0xff00n);
// DIV pops b then a: [0x10000, 4] -> 0x10000 / 4.
addFixture('math_div', program(push(0x10000), push(4), div), 'ok', 0x4000n);
addFixture('math_div_by_zero', program(push(8), push(0), div), 'ok', 0n);
addFixture('math_wrap_underflow', program(push(0), push(1), sub), 'ok', 2n ** 256n - 1n);
addFixture('stack_dup_add', program(push(5), dup(1), add), 'ok', 10n);
addFixture(
  'stack_swap_sub',
  // [7,9] after two pushes; SWAP2 -> [9,7]; SUB -> 9 - 7 = 2.
  program(push(7), push(9), swap(2), sub),
  'ok',
  2n,
);
addFixture('push32_max', program(push(2n ** 256n - 1n)), 'ok', 2n ** 256n - 1n);

// --- Memory and hashing -------------------------------------------------------

addFixture(
  'memory_store_load',
  program(
    blob(new Uint8Array(32)),
    pop, // drop len -> [offset]
    dup(1), // [offset, offset]
    push(0x123456n),
    mstore,
    mload,
  ),
  'ok',
  0x123456n,
);
addFixture('keccak_empty_blob', program(blob(new Uint8Array(0)), keccak256, pop), 'ok');

// --- Labels: forward, backward, JZ both directions ----------------------------

addFixture(
  'labels_forward_skip',
  // If the jump is broken, the poison PUSH69 makes the result 72 instead of 3.
  program(push(1), push(2), jmp('skip'), push(69), label('skip'), add),
  'ok',
  3n,
);

addFixture(
  'labels_forward_to_end',
  // Jumping to the final label lands on STOP appended by addFixture.
  program(push(1), jmp('end'), push(2), label('end')),
  'ok',
  1n,
);

addFixture(
  'labels_backward_loop',
  // acc = 0; i = 3; head: if (i == 0) done; acc += 1; i -= 1; jmp head;
  program(
    push(0),
    push(3),
    label('head'),
    dup(1),
    jz('done'),
    swap(2),
    push(1),
    add,
    swap(2),
    push(1),
    sub,
    jmp('head'),
    label('done'),
    pop, // drop i -> [acc]
  ),
  'ok',
  3n,
);

addFixture(
  'jz_not_taken_then_forward_jmp',
  // cond = (1 == 1) = 1 -> JZ falls through: 40 + 2 = 42, then skips the 5+add.
  program(
    push(40),
    push(1),
    push(1),
    eq,
    jz('zero'),
    push(2),
    add,
    jmp('end'),
    label('zero'),
    push(5),
    add,
    label('end'),
  ),
  'ok',
  42n,
);

addFixture(
  'jz_taken_skips_poison',
  // cond = 0 -> jumps over push/add, leaving 42 (broken JZ would give 43).
  program(push(42), push(0), jz('t'), push(1), add, label('t')),
  'ok',
  42n,
);

// --- Malformed bytecode and runtime guards ------------------------------------

addFixture('invalid_opcode', program(raw('0x3a')), 'revert');
addFixture('truncated_push32', program(raw('0x20')), 'revert');
addFixture('truncated_blob', program(raw('0x2d00ff')), 'revert');
addFixture('stack_underflow_pop', program(pop), 'revert');
addFixture('stack_overflow', program(Array.from({ length: 17 }, () => push(0))), 'revert');
addFixture('dup_zero_operand', program(raw('0x2200')), 'revert');
addFixture('jmp_forward_out_of_bounds', program(raw('0x2b0004')), 'revert');
addFixture('jmp_backward_underflow', program(raw('0x2bffff')), 'revert'); // -32767 from byte 1
addFixture('memory_offset_wrap', program(push(2n ** 256n - 0x260n), mload), 'revert');
addFixture('revert_opcode', program(raw('0x39')), 'revert');

// --- Emit ---------------------------------------------------------------------

const rows = fixtures.map(
  (f) =>
    `    {"name": ${JSON.stringify(f.name)}, "program": "0x${hex(f.program)}", "expect": "${f.expect}"` +
    (f.expectA !== undefined ? `, "expectA": ${f.expectA.toString()}` : '') +
    '}',
);

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dest = join(root, 'build', 'fixtures', 'tooling.json');
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, `{"count": ${fixtures.length}, "programs": [\n${rows.join(',\n')}\n]}\n`);
console.log(`Wrote ${fixtures.length} fixture programs to ${dest}`);

function hex(bytes: Uint8Array): string {
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
}
