interface Fixture {
  name: string;
  program: Uint8Array;
  expect: 'ok' | 'revert';
  /** When set, the Solidity harness writes the stack top to `a` and asserts it. */
  expectA?: bigint;
  /** When set, the harness asserts its `recordedAmount` mock storage slot. */
  expectRecorded?: bigint;
}

const fixtures: Fixture[] = [];
function addFixture(
  name: string,
  body: Program,
  expect: 'ok' | 'revert',
  expectA?: bigint,
  expectRecorded?: bigint,
): void {
  // With expectA, the Foundry harness appends its own write-top-to-`a` tail
  // (ending in CALL+STOP), so the body must fall through into it; a trailing
  // STOP would end execution before the tail runs. Revert fixtures get no
  // trailing STOP either — it would patch malformed programs back into valid
  // ones (a truncated `2b` would become a complete JMP +0).
  const tail = expect === 'ok' && expectA === undefined ? [stop] : [];
  const bytes = compile(program(body, tail)).bytes;
  // Self-check: decodable generated bytecode must survive a decode round-trip.
  try {
    for (const instr of decode(bytes)) void instr;
  } catch (err) {
    if (expect !== 'revert') throw err;
  }
  fixtures.push({ name, program: bytes, expect, expectA, expectRecorded });
}

